#!/usr/bin/env bash
# Creates local development secrets. LOCAL DEVELOPMENT ONLY.
# 1. Generates random values into .env (gitignored) for docker compose. Existing values are kept.
# 2. Stores connection strings and the client secret as .NET user secrets for `dotnet run`.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="$root/.env"
names=(POSTGRES_PASSWORD ESTIMATES_DB_PASSWORD ACCOUNTING_DB_PASSWORD KEYCLOAK_ADMIN_PASSWORD DEMO_USER_PASSWORD ACCOUNTING_SERVICE_CLIENT_SECRET)

new_secret() {
  # URL-safe characters only, so the value works in connection strings and shell commands.
  openssl rand -base64 24 | tr '+/' 'AB' | tr -d '=\n'
}

declare -A values
if [[ -f "$env_file" ]]; then
  while IFS='=' read -r key value; do
    if [[ "$key" =~ ^[A-Z_]+$ && -n "${value:-}" ]]; then
      values[$key]="$value"
    fi
  done < "$env_file"
fi

{
  echo "# LOCAL DEVELOPMENT SECRETS - generated by scripts/init-dev-env.sh. Never commit this file."
  for name in "${names[@]}"; do
    if [[ -z "${values[$name]:-}" ]]; then
      values[$name]="$(new_secret)"
    fi
    echo "$name=${values[$name]}"
  done
} > "$env_file"
echo "Wrote $env_file"

dotnet user-secrets set "ConnectionStrings:EstimatesDb" \
  "Host=localhost;Port=55432;Database=estimates;Username=estimates_app;Password=${values[ESTIMATES_DB_PASSWORD]}" \
  --project "$root/src/Estimates/Estimates.Api" > /dev/null
dotnet user-secrets set "ConnectionStrings:AccountingDb" \
  "Host=localhost;Port=55432;Database=accounting;Username=accounting_app;Password=${values[ACCOUNTING_DB_PASSWORD]}" \
  --project "$root/src/Accounting/Accounting.Api" > /dev/null
dotnet user-secrets set "EstimatesService:ClientSecret" "${values[ACCOUNTING_SERVICE_CLIENT_SECRET]}" \
  --project "$root/src/Accounting/Accounting.Api" > /dev/null
for project in Estimates/Estimates.Api Accounting/Accounting.Api; do
  dotnet user-secrets set "DevelopmentToken:DefaultPassword" "${values[DEMO_USER_PASSWORD]}" \n    --project "$root/src/$project" > /dev/null
done
echo "Stored connection strings, the Accounting client secret and the demo user password as .NET user secrets."
echo "Note: if the PostgreSQL volume already exists with other passwords, run 'docker compose down -v' first."
