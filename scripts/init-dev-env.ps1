<#
.SYNOPSIS
  Creates local development secrets. LOCAL DEVELOPMENT ONLY.

.DESCRIPTION
  1. Generates random passwords and the Accounting service client secret into .env (gitignored),
     which docker compose reads. Existing values are kept, so re-running is safe.
  2. Stores the connection strings and client secret as .NET user secrets, so the APIs can also
     be started with `dotnet run` outside Docker. User secrets live in your user profile, not the repo.
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'

function New-Secret {
    # Works in both Windows PowerShell 5.1 (.NET Framework) and PowerShell 7.
    $bytes = New-Object byte[] 24
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $generator.GetBytes($bytes)
    $generator.Dispose()
    # URL-safe characters only, so the value works in connection strings and shell commands.
    return [Convert]::ToBase64String($bytes).Replace('+', 'A').Replace('/', 'B').Replace('=', '')
}

$names = @('POSTGRES_PASSWORD', 'ESTIMATES_DB_PASSWORD', 'ACCOUNTING_DB_PASSWORD', 'KEYCLOAK_ADMIN_PASSWORD', 'DEMO_USER_PASSWORD', 'ACCOUNTING_SERVICE_CLIENT_SECRET')
$values = [ordered]@{}
if (Test-Path $envFile) {
    foreach ($line in Get-Content $envFile) {
        if ($line -match '^\s*([A-Z_]+)=(.*)$' -and $Matches[2] -ne '') {
            $values[$Matches[1]] = $Matches[2]
        }
    }
}
foreach ($name in $names) {
    if (-not $values.Contains($name)) {
        $values[$name] = New-Secret
    }
}

$lines = @('# LOCAL DEVELOPMENT SECRETS - generated by scripts/init-dev-env.ps1. Never commit this file.')
foreach ($name in $names) {
    $lines += "$name=$($values[$name])"
}
# UTF-8 without a byte-order mark: Docker Compose's .env parser does not expect one.
[System.IO.File]::WriteAllLines($envFile, [string[]]$lines, (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $envFile"

$estimatesApi = Join-Path $root 'src/Estimates/Estimates.Api'
$accountingApi = Join-Path $root 'src/Accounting/Accounting.Api'
dotnet user-secrets set 'ConnectionStrings:EstimatesDb' "Host=localhost;Port=55432;Database=estimates;Username=estimates_app;Password=$($values['ESTIMATES_DB_PASSWORD'])" --project $estimatesApi | Out-Null
dotnet user-secrets set 'ConnectionStrings:AccountingDb' "Host=localhost;Port=55432;Database=accounting;Username=accounting_app;Password=$($values['ACCOUNTING_DB_PASSWORD'])" --project $accountingApi | Out-Null
dotnet user-secrets set 'EstimatesService:ClientSecret' $values['ACCOUNTING_SERVICE_CLIENT_SECRET'] --project $accountingApi | Out-Null
foreach ($project in @($estimatesApi, $accountingApi)) {
    dotnet user-secrets set 'DevelopmentToken:DefaultPassword' $values['DEMO_USER_PASSWORD'] --project $project | Out-Null
}
Write-Host 'Stored connection strings, the Accounting client secret and the demo user password as .NET user secrets.'
Write-Host 'Note: if the PostgreSQL volume already exists with other passwords, run "docker compose down -v" first.'
