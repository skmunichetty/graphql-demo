using Estimates.Domain;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Estimates.Infrastructure.Persistence;

/// <summary>
/// EF Core context for the Estimates service's own database ("estimates").
/// No other service may connect to this database: other services use the GraphQL API.
/// </summary>
public sealed class EstimatesDbContext : DbContext
{
    public EstimatesDbContext(DbContextOptions<EstimatesDbContext> options)
        : base(options)
    {
    }

    public DbSet<Estimate> Estimates => Set<Estimate>();

    public DbSet<LineItem> LineItems => Set<LineItem>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        ConfigureEstimate(modelBuilder.Entity<Estimate>());
        ConfigureLineItem(modelBuilder.Entity<LineItem>());
    }

    private static void ConfigureEstimate(EntityTypeBuilder<Estimate> estimate)
    {
        estimate.ToTable("estimates", table =>
        {
            // Database constraints repeat the most important domain rules. The domain gives friendly
            // errors; the database guarantees integrity even if a bug bypasses the domain.
            table.HasCheckConstraint("ck_estimates_status", "status IN ('Draft', 'Approved')");
            table.HasCheckConstraint("ck_estimates_currency_code", "char_length(currency_code) = 3");
            table.HasCheckConstraint("ck_estimates_version_positive", "version > 0");
            table.HasCheckConstraint(
                "ck_estimates_approved_at",
                "(status = 'Approved' AND approved_at IS NOT NULL) OR (status <> 'Approved' AND approved_at IS NULL)");
        });

        estimate.HasKey(item => item.Id);

        // IDs are generated by the domain (Guid version 7). ValueGeneratedNever tells EF Core that a
        // new entity with a non-empty key is still new, so it is INSERTed rather than UPDATEd.
        estimate.Property(item => item.Id).HasColumnName("id").ValueGeneratedNever();
        estimate.Property(item => item.TenantId).HasColumnName("tenant_id").HasMaxLength(64).IsRequired();
        estimate.Property(item => item.CurrencyCode).HasColumnName("currency_code").HasMaxLength(3).IsFixedLength().IsRequired();
        estimate.Property(item => item.Status).HasColumnName("status").HasConversion<string>().HasMaxLength(20).IsRequired();
        estimate.Property(item => item.Subtotal).HasColumnName("subtotal").HasPrecision(18, 2);
        estimate.Property(item => item.TaxTotal).HasColumnName("tax_total").HasPrecision(18, 2);
        estimate.Property(item => item.Total).HasColumnName("total").HasPrecision(18, 2);
        estimate.Property(item => item.CreatedAt).HasColumnName("created_at");
        estimate.Property(item => item.UpdatedAt).HasColumnName("updated_at");
        estimate.Property(item => item.ApprovedAt).HasColumnName("approved_at");

        // Optimistic concurrency: EF Core adds "WHERE version = <original>" to every UPDATE.
        // If another request saved first, zero rows match and EF throws DbUpdateConcurrencyException.
        estimate.Property(item => item.Version).HasColumnName("version").IsConcurrencyToken();

        estimate.OwnsOne(item => item.Customer, customer =>
        {
            customer.Property(details => details.Name).HasColumnName("customer_name").HasMaxLength(EstimateRules.MaxCustomerNameLength).IsRequired();
            customer.Property(details => details.Email).HasColumnName("customer_email").HasMaxLength(EstimateRules.MaxCustomerEmailLength);
            customer.Property(details => details.Phone).HasColumnName("customer_phone").HasMaxLength(EstimateRules.MaxCustomerPhoneLength);
        });
        estimate.Navigation(item => item.Customer).IsRequired();

        estimate.HasMany(item => item.LineItems)
            .WithOne()
            .HasForeignKey(lineItem => lineItem.EstimateId)
            .OnDelete(DeleteBehavior.Cascade);

        // The domain exposes a read-only list; EF Core writes to the private backing field.
        estimate.Navigation(item => item.LineItems).UsePropertyAccessMode(PropertyAccessMode.Field);

        // Supports the tenant-filtered, newest-first list query used by cursor pagination.
        estimate.HasIndex(item => new { item.TenantId, item.CreatedAt, item.Id })
            .HasDatabaseName("ix_estimates_tenant_created_id")
            .IsDescending(false, true, true);
    }

    private static void ConfigureLineItem(EntityTypeBuilder<LineItem> lineItem)
    {
        lineItem.ToTable("line_items", table =>
        {
            table.HasCheckConstraint("ck_line_items_quantity_positive", "quantity > 0");
            table.HasCheckConstraint("ck_line_items_unit_price_non_negative", "unit_price >= 0");
            table.HasCheckConstraint("ck_line_items_tax_rate_range", "tax_rate_percent >= 0 AND tax_rate_percent <= 100");
            table.HasCheckConstraint("ck_line_items_total", "total = subtotal + tax_amount");
        });

        lineItem.HasKey(item => item.Id);
        lineItem.Property(item => item.Id).HasColumnName("id").ValueGeneratedNever();
        lineItem.Property(item => item.EstimateId).HasColumnName("estimate_id");
        lineItem.Property(item => item.TenantId).HasColumnName("tenant_id").HasMaxLength(64).IsRequired();
        lineItem.Property(item => item.Position).HasColumnName("position");
        lineItem.Property(item => item.Description).HasColumnName("description").HasMaxLength(EstimateRules.MaxDescriptionLength).IsRequired();

        // Inputs allow 4 decimal places; money amounts are stored with exactly 2.
        lineItem.Property(item => item.Quantity).HasColumnName("quantity").HasPrecision(18, 4);
        lineItem.Property(item => item.UnitPrice).HasColumnName("unit_price").HasPrecision(18, 4);
        lineItem.Property(item => item.TaxRatePercent).HasColumnName("tax_rate_percent").HasPrecision(9, 4);
        lineItem.Property(item => item.Subtotal).HasColumnName("subtotal").HasPrecision(18, 2);
        lineItem.Property(item => item.TaxAmount).HasColumnName("tax_amount").HasPrecision(18, 2);
        lineItem.Property(item => item.Total).HasColumnName("total").HasPrecision(18, 2);

        lineItem.HasIndex(item => new { item.TenantId, item.EstimateId }).HasDatabaseName("ix_line_items_tenant_estimate");
    }
}
